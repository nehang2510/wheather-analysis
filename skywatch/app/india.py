def capitals() -> list[Place]:
    return [
        Place(name=cities[0][0], admin1=state, country="India", latitude=cities[0][1], longitude=cities[0][2])
        for state, cities in INDIA.items()
    ]


def as_places() -> dict[str, list[dict]]:
    return {
        state: [{"name": n, "latitude": la, "longitude": lo} for n, la, lo in cities] for state, cities in INDIA.items()
    }
